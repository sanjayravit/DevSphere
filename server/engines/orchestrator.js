import { createHash, randomUUID } from 'node:crypto';
import { processIntent } from './intentEngine.js';
import { plannerAgent } from '../agents/plannerAgent.js';
import { devAgent } from '../agents/devAgent.js';
import { qaAgent } from '../agents/qaAgent.js';
import { analyzeSystem } from './designEngine.js';
import { evaluateDecision } from './decisionEngine.js';
import { createUniqueBranch, commitChanges, createPullRequest } from '../services/githubService.js';
import { appendRunEvent, createRun, updateRun } from '../services/firebaseService.js';

const canonicalize = value => Array.isArray(value) ? value.map(canonicalize) : value && typeof value === 'object' ? Object.fromEntries(Object.keys(value).sort().map(key => [key, canonicalize(value[key])])) : value;
export const proposalHash = (changes) => createHash('sha256').update(JSON.stringify(canonicalize(changes))).digest('hex');

async function progress({ runId, userId, emit, appendEvent = appendRunEvent }, step, status, detail = {}) {
  const event = { runId, step, status, detail, at: new Date().toISOString() };
  await appendEvent(runId, userId, event);
  emit?.(event);
}

async function executeChanges({ runId, userId, emit, appendEvent = appendRunEvent, update = updateRun, createBranch = createUniqueBranch, commitFn = commitChanges, openPullRequest = createPullRequest }, proposal) {
  const context = { runId, userId, emit, appendEvent };
  await progress(context, 'github-branch', 'running', { message: 'Creating a feature branch from the current default branch.' });
  const branch = await createBranch(proposal.repository, proposal.defaultBranch);
  await update(runId, userId, { branch: branch.branch, baseBranch: branch.base, branchUrl: branch.url, baseSha: branch.baseSha });
  await progress(context, 'github-commit', 'running', { branch: branch.branch });
  let commitResult;
  try {
    commitResult = await commitFn(proposal.repository, branch.branch, proposal.changes);
  } catch (error) {
    if (error.partialCommit) await update(runId, userId, { commitSha: error.partialCommit.sha, commitUrl: error.partialCommit.html_url, partialCommitPaths: error.partialPaths || [], executionError: error.message });
    throw error;
  }
  await update(runId, userId, { commitSha: commitResult.commitSha, commitUrl: commitResult.commitUrl, branchUrl: commitResult.branchUrl });
  await progress(context, 'github-pr', 'running', { commitUrl: commitResult.commitUrl });
  const pr = await openPullRequest(proposal.repository, branch.branch, branch.base, {
    title: `DevSphere V2: ${proposal.intent.summary.slice(0, 160)}`,
    body: `## DevSphere V2 proposal\n\n${proposal.intent.summary}\n\n**Decision:** ${proposal.decision.decision} — ${proposal.decision.reason}\n**Confidence:** ${proposal.decision.confidence}%\n**Risk / impact:** ${proposal.decision.risk} / ${proposal.decision.impact}\n**QA:** ${proposal.qa.status} (static checks; see run details)\n\nGenerated by DevSphere. Review this pull request and required CI checks before merging.`
  });
  const urls = { branch: branch.url, commit: commitResult.commitUrl, pullRequest: pr.url, pullNumber: pr.number, commitSha: commitResult.commitSha };
  await update(runId, userId, { status: 'pull_request', approval: proposal.approval || 'not-required', branch: branch.branch, baseBranch: branch.base, ...urls, executionError: null });
  await progress(context, 'github-pr', 'completed', { ...urls });
  return urls;
}

export function createRunDevSphere(overrides = {}) {
  const dependencies = { processIntent, plannerAgent, devAgent, qaAgent, analyzeSystem, evaluateDecision, createUniqueBranch, commitChanges, createPullRequest, appendRunEvent, createRun, updateRun, ...overrides };
  return async function runDevSphere({ input, mode, userId, emit }) {
  const runId = randomUUID();
  const owner = String(userId);
  await dependencies.createRun(runId, { userId: owner, input, mode, status: 'running', approval: 'not-required', steps: [], proposal: null });
  const context = { runId, userId: owner, emit, appendEvent: dependencies.appendRunEvent, update: dependencies.updateRun, createBranch: dependencies.createUniqueBranch, commitFn: dependencies.commitChanges, openPullRequest: dependencies.createPullRequest };
  try {
    await progress(context, 'intent', 'running');
    const intent = await dependencies.processIntent(input);
    await progress(context, 'intent', 'completed', { summary: intent.summary });

    await progress(context, 'planner', 'running');
    const plan = await dependencies.plannerAgent(intent);
    await progress(context, 'planner', 'completed', { taskCount: plan.tasks.length });

    await progress(context, 'developer', 'running');
    const repo = process.env.GITHUB_REPOSITORY;
    const devOutput = await dependencies.devAgent({ repo, intent, plan });
    await progress(context, 'developer', 'completed', { changeCount: devOutput.changes.length, repository: devOutput.repository });

    await progress(context, 'qa', 'running');
    const qa = await dependencies.qaAgent(devOutput);
    await progress(context, 'qa', qa.status, { summary: qa.summary, checkCount: qa.checks.length });

    await progress(context, 'design', 'running');
    const design = dependencies.analyzeSystem({ plan, changes: devOutput.changes, qa });
    await progress(context, 'design', 'completed', { suggestions: design.suggestions });

    const decision = dependencies.evaluateDecision({ confidence: design.confidence, risk: design.risk, impact: design.impact, mode, qa });
    const hash = proposalHash(devOutput.changes);
    const proposal = {
      issue: design.issue, suggestedFix: design.suggestedFix,
      confidence: design.confidence, risk: design.risk, impact: design.impact,
      decision, changes: devOutput.changes, qa, design,
      intent: { summary: intent.summary },
      repository: devOutput.repository, defaultBranch: devOutput.defaultBranch
    };
    const awaitingApproval = decision.decision === 'ask';
    const status = awaitingApproval ? 'pending_approval' : decision.decision === 'auto' ? 'executing' : decision.decision === 'block' ? 'blocked' : 'suggested';
    await dependencies.updateRun(runId, owner, { status, intent, plan, decision, qa, proposal, approvalHash: awaitingApproval ? hash : null, approval: awaitingApproval ? 'pending' : 'not-required' });
    await progress(context, 'decision', 'completed', { ...decision, approvalRequired: awaitingApproval });

    if (decision.decision === 'auto') {
      const urls = await executeChanges(context, { ...proposal, approval: 'not-required' });
      return { runId, status: 'pull_request', intent, plan, proposal, qa, decision, ...urls };
    }
    return { runId, status, intent, plan, proposal, qa, decision, approvalHash: awaitingApproval ? hash : undefined };
  } catch (error) {
    const message = error?.message || 'DevSphere run failed.';
    try {
      await progress(context, 'orchestrator', 'failed', { message });
      await dependencies.updateRun(runId, owner, { status: 'failed', error: message });
    } catch { /* Preserve the original error if persistence itself has failed. */ }
    error.runId = runId;
    throw error;
  }
  };
}

export const runDevSphere = createRunDevSphere();

export async function executeApprovedRun({ run, userId, emit }) {
  const context = { runId: run.id, userId: String(userId), emit };
  if (!run.proposal || run.decision?.decision !== 'ask' || run.qa?.status !== 'passed' || run.approval !== 'approved' || run.approvalHash !== proposalHash(run.proposal.changes)) throw new Error('This proposal is not eligible for approval execution.');
  const urls = await executeChanges(context, { ...run.proposal, approval: 'approved' });
  return { runId: run.id, status: 'pull_request', ...urls };
}
