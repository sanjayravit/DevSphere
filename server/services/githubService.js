// Actual GitHub API implementation using axios
const axios = require('axios');

async function createPullRequest(repoName, fixedCode, branchName, commitMessage) {
    console.log(`[GitHub Service] Initiating Auto-PR for ${repoName}`);

    const token = process.env.GITHUB_TOKEN;
    if (!token) {
        console.warn(`[GitHub Service] GITHUB_TOKEN not found. Simulating PR creation for ${repoName}`);
        return `https://github.com/simulated-pr/${branchName}`;
    }

    try {
        const headers = {
            Authorization: `token ${token}`,
            Accept: 'application/vnd.github.v3+json'
        };

        // 1. Get the repository info to find the default branch
        const repoRes = await axios.get(`https://api.github.com/repos/${repoName}`, { headers });
        const defaultBranchName = repoRes.data.default_branch;

        // 2. Get the commit SHA of the default branch
        const branchRes = await axios.get(`https://api.github.com/repos/${repoName}/git/ref/heads/${defaultBranchName}`, { headers });
        const baseSha = branchRes.data.object.sha;

        // 3. Create a new branch pointing to the base SHA
        await axios.post(`https://api.github.com/repos/${repoName}/git/refs`, {
            ref: `refs/heads/${branchName}`,
            sha: baseSha
        }, { headers });

        // 4. Update the target file in the new branch (Assuming single file fix for MVP)
        // Hardcoded 'index.js' for MVP as we don't have the original file path easily in this context unless passed.
        // For a true implementation, `file` would be passed from errorAgent.
        const filePath = "index.js"; // This should ideally be passed downwards from errorAgent

        // We attempt to get the file SHA if it exists
        let fileSha = null;
        try {
            const fileRes = await axios.get(`https://api.github.com/repos/${repoName}/contents/${filePath}?ref=${branchName}`, { headers });
            fileSha = fileRes.data.sha;
        } catch (e) {
            // File might not exist, ignore
        }

        const contentBase64 = Buffer.from(fixedCode).toString('base64');
        const fileUpdatePayload = {
            message: commitMessage,
            content: contentBase64,
            branch: branchName
        };
        if (fileSha) fileUpdatePayload.sha = fileSha;

        await axios.put(`https://api.github.com/repos/${repoName}/contents/${filePath}`, fileUpdatePayload, { headers });

        // 5. Open a Pull Request
        const prRes = await axios.post(`https://api.github.com/repos/${repoName}/pulls`, {
            title: `Fix: ${commitMessage}`,
            head: branchName,
            base: defaultBranchName,
            body: `Automated fix generated by DevSphere based on identified errors.\n\nBranch: ${branchName}`
        }, { headers });

        console.log(`[GitHub Service] PR created successfully: ${prRes.data.html_url}`);
        return prRes.data.html_url;

    } catch (error) {
        console.error(`[GitHub Service] Error creating PR:`, error.response?.data || error.message);
        return `https://github.com/simulated-pr/error-fallback-${branchName}`;
    }
}

module.exports = { createPullRequest };
